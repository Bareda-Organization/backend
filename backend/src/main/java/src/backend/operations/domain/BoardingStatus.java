package src.backend.operations.domain;

/**
 * 관리자 화면이 학생 1명의 승하차 진행 상태를 표시할 때 쓰는 5단계 판정.
 * {@link BoardingStatusResolver#resolve}가 이 값을 계산한다.
 *
 * <p><b>{@code ABSENT}와 {@code NO_SHOW}는 반드시 구분한다.</b> 전자는 학부모가 사전에 결석을
 * 신고해 승인된 경우로 학부모 알림 대상이 아니고(관계자만 통지), 후자는 사전 신고 없이 정류소에서
 * 확인되지 않은 경우로 즉시 알림과 3분 에스컬레이션 대상이다. 둘을 합쳐 표시하면 화면과 알림이
 * 서로 다른 기준으로 "누락"을 말하게 되고, 사전에 안 탄다고 한 학생을 두고 관계자가 헛되이
 * 학부모에게 연락하는 결과로 이어진다.
 */
public enum BoardingStatus {

    /**
     * 당일 승인된 결석 신고 존재 — 학부모가 사전에 OFF 처리, 학부모 알림 없음(관계자만 통지).
     * 승하차 기록 유무와 무관하게 다른 모든 조건보다 우선한다.
     */
    ABSENT,

    /** 하차(ALIGHT) 또는 보호자 인계완료(HANDOVER) 기록 존재. */
    ALIGHTED,

    /** 승차(BOARD) 기록은 존재하나 하차 기록은 부재. */
    BOARDED,

    /** 기록 부재 + 정차 도달 + 경과 시간이 임계값 이상 — 현장 미승차. 즉시 알림 + 3분 에스컬레이션 대상. */
    NO_SHOW,

    /** 그 밖의 모든 경우 — 기록 부재 + 정차 미도달, 도달했으나 경과가 임계값 미만, 또는 세션 미시작. */
    WAITING
}
